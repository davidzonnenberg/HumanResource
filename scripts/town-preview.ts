// Build the 2D town preview from the real TypeScript (T2).
//
//   npm.cmd run town:preview              writes docs/previews/town-map-preview.html
//   npm.cmd run town:preview -- --check   exits 1 when the committed page is out of date (does not write)
//
// The page bundles apps/web/src/render/procedural/town/preview/main.ts (the same generateTown / applyOverrides that
// `town:bake` uses) together with the committed town-brief.json and town-overrides.json. Never edit the HTML by hand.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';
import { lockedBuildings } from '../apps/web/src/render/procedural/town/applyOverrides';
import { parseTownBrief, parseTownData, parseTownOverrides } from '../apps/web/src/render/procedural/town/townSchema';
import { PREVIEW_CSS } from '../apps/web/src/render/procedural/town/preview/townPreview';
// @ts-expect-error - plain ESM helper without type declarations
import { cacheDir } from './cacheDir.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(root, 'apps/web/src/render/procedural/town/preview/main.ts');
const outPath = resolve(root, 'docs/previews/town-map-preview.html');
const check = process.argv.includes('--check');

// The locked buildings of the committed bake: `town:bake --force` passes them to the generator, so the page needs them
// to give the same town (and the same counts) as the bake.
const maps = resolve(root, 'packages/content/data/maps');
const brief = parseTownBrief(JSON.parse(readFileSync(resolve(maps, 'town-brief.json'), 'utf8')));
const overrides = parseTownOverrides(JSON.parse(readFileSync(resolve(maps, 'town-overrides.json'), 'utf8')));
const bakePath = resolve(maps, 'generated', `town-${brief.id}.json`);
const locked = existsSync(bakePath) ? lockedBuildings(parseTownData(JSON.parse(readFileSync(bakePath, 'utf8'))), overrides) : [];

const result = await build({
  configFile: false,
  define: { __TOWN_LOCKED__: JSON.stringify(locked) },
  root,
  logLevel: 'warn',
  cacheDir: cacheDir('vite-town-preview') as string,
  build: {
    write: false,
    target: 'es2022',
    minify: true,
    lib: { entry, name: 'TownPreview', formats: ['iife'], fileName: 'town-preview' },
  },
});
const outputs = (Array.isArray(result) ? result : [result]).flatMap((r) => ('output' in r ? r.output : []));
const chunk = outputs.find((o) => o.type === 'chunk');
if (!chunk || chunk.type !== 'chunk') throw new Error('town preview: the bundle has no JavaScript chunk');
const js = chunk.code.replace(/<\/script/gi, '<\\/script');

const html = `<!doctype html>
<!-- GENERATED by "npm.cmd run town:preview" from apps/web/src/render/procedural/town/preview/. Do not edit by hand. -->
<html><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'><title>Town map preview</title><style>${PREVIEW_CSS}</style></head><body style='margin:0;padding:12px;background:#eee'><div id='tm-root'></div><script>${js}</script></body></html>
`;

if (check) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (current !== html) {
    console.error('docs/previews/town-map-preview.html is out of date. Run: npm.cmd run town:preview');
    process.exit(1);
  }
  console.log('docs/previews/town-map-preview.html is up to date.');
} else {
  writeFileSync(outPath, html);
  console.log(`wrote ${outPath} (${Math.round(html.length / 1024)} KB)`);
}
